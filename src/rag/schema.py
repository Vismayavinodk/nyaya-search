"""
Schema definitions for the Legal Question-Answering and RAG Layer.
Separated cleanly from the core retrieval and ranking pipeline.
"""

from __future__ import annotations
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class LegalQAExample(BaseModel):
    """
    Benchmark test example for legal question answering and hallucination auditing.
    """
    question_id: str
    question: str
    gold_answer: str
    gold_doc_ids: List[str] = Field(default_factory=list)
    is_answerable: bool = True
    domain: str = "Constitutional Law"
    cited_statutes: List[str] = Field(default_factory=list)
    evidence_text: Optional[str] = None


class RAGPassage(BaseModel):
    """
    Retrieved document snippet or case precedent context.
    """
    doc_id: str
    title: str
    text: str
    score: float
    court: Optional[str] = None
    year: Optional[int] = None


class RAGResponse(BaseModel):
    """
    Output generated by the Legal RAG Engine.
    """
    model_config = {"protected_namespaces": ()}

    question_id: str
    question: str
    answer: str
    cited_doc_ids: List[str] = Field(default_factory=list)
    is_refusal: bool = False
    evidence_score: float = 0.0
    faithfulness_score: float = 1.0
    retrieved_passages: List[Dict[str, Any]] = Field(default_factory=list)
    model_name: str = "flan-t5-small"
